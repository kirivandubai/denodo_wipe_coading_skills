class ResolveTest(unittest.TestCase):
    def setUp(self):
        reset_server()
        self.dir = Path(tempfile.mkdtemp())
        self.path = self.dir / "chain.toml"

    def chain(self, text=RUN):
        self.path.write_text(text, encoding="utf-8")
        return load_chain(self.path)

    def run_it(self, chain=None, **kw):
        kw.setdefault("with_writes", True)
        return run_chain(profile(), chain or self.chain(), root=self.dir, vql_factory=Server, **kw)

    def test_a_manifest_without_markers_or_requirements_asks_the_server_nothing(self):
        chain = self.chain('[values]\ndatabase = "d"\n[[step]]\nid = "a"\nkind = "fixture"\n'
                           'channel = "vql"\nvql = "SELECT 1;"\n')
        doc, code = self.run_it(chain)
        self.assertEqual(code, 0)
        self.assertFalse(any("VALIDATE_MPP_LICENSE" in s or "GET_PARAMETER" in s for s in Server.sent))
        self.assertNotIn("features", doc)

    def test_server_values_and_where_each_came_from(self):
        doc, code = self.run_it()
        self.assertEqual(code, 0, doc)
        self.assertIn("SELECT EMBED_AI('x', 'text-embedding-3-large')", Server.sent)
        self.assertIn("CREATE REMOTE TABLE t CATALOG = 'enterprise_data' (id INT IDENTITY(1001,1))", Server.sent)
        self.assertEqual(doc["values_from"]["embedding_model"], "server")
        self.assertEqual(doc["values_from"]["write_identity"], "dialect")
        self.assertEqual(doc["values_from"]["database"], "manifest")
        self.assertEqual(doc["features"]["cache"]["adapter"], "sqlserver")
        self.assertEqual(doc["summary"]["not_run"], 2)

    def test_the_dialect_follows_the_product(self):
        reset_server(adapter="postgresql")
        self.run_it()
        self.assertIn("CREATE REMOTE TABLE t CATALOG = 'enterprise_data' "
                      "(id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001))", Server.sent)

    def test_the_values_file_beats_the_server_and_the_flag_beats_the_file(self):
        doc, _ = self.run_it(file_values={"embedding_model": "my-model", "database": "from_file"},
                             values_file=self.dir / "verify.toml", database="from_flag")
        self.assertIn("SELECT EMBED_AI('x', 'my-model')", Server.sent)
        self.assertEqual(doc["values_from"]["embedding_model"], "file")
        self.assertEqual(doc["values"]["database"], "from_flag")
        self.assertEqual(doc["values_file"], str(self.dir / "verify.toml"))

    def test_an_unknown_product_leaves_the_dialect_value_unresolved_and_skips_its_step(self):
        reset_server(adapter="oracle")
        doc, code = self.run_it(values_file=self.dir / "verify.toml")
        self.assertEqual(code, 0, doc)
        table = next(s for s in doc["steps"] if s["id"] == "table")
        self.assertTrue(table["skipped"])
        self.assertIn("write_identity", table["reason"])
        self.assertIn("oracle", table["reason"])
        self.assertIn(str(self.dir / "verify.toml"), table["reason"])
        self.assertFalse(next(s for s in doc["steps"] if s["id"] == "after")["skipped"])
        self.assertFalse(any("{write_identity}" in s for s in Server.sent))
        self.assertEqual(doc["values_from"]["write_identity"], "unresolved")

    def test_a_non_administrator_leaves_server_settings_unresolved(self):
        reset_server(settings=None)
        doc, code = self.run_it()
        self.assertEqual(code, 0, doc)
        embed = next(s for s in doc["steps"] if s["id"] == "embed")
        self.assertTrue(embed["skipped"])
        self.assertIn("embedding_model", embed["reason"])
        self.assertIsNone(doc["features"]["llm"])

    def test_a_cleanup_statement_naming_an_unresolved_value_is_reported_not_sent(self):
        reset_server(catalog=None)
        doc, code = self.run_it()
        self.assertEqual(code, 0, doc)
        self.assertFalse(any("{write_catalog}" in s for s in Server.sent))
        skipped = [s for s in doc["cleanup"]["statements"] if s.get("skipped")]
        self.assertEqual(len(skipped), 1)
        self.assertIn("write_catalog", skipped[0]["reason"])
        self.assertIn("DROP DATABASE IF EXISTS denodo_skills_test CASCADE", Server.sent)


