"""Where the chain's values come from (T40): the manifest, the server, a local values file.

The manifest keeps what belongs to the chain; a value of one installation is a marker the run
fills in — ``@server`` from what the server says, ``@dialect`` from the manifest's dialect table
of the write data source's product — and the per-profile values file beside the profiles
overrides any of them. A value nobody filled in makes the steps that name it skip, saying which
line to add where; a text with a placeholder in it is never sent.
"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from denodo_cli.commands.verify import ChainError, load_chain, load_values_file, run_chain
from denodo_cli.profiles import Profile
from denodo_cli.transports.base import HttpResult, VqlResult

MANIFEST = """
[values]
database = "denodo_skills_test"
fixture_base = "https://example.org/data"
write_dialect = "@server"
write_identity = "@dialect"

[dialects.sqlserver]
write_identity = "INT IDENTITY(1001,1)"

[dialects.postgresql]
write_identity = "INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001)"
write_timestamp = "TIMESTAMP(0)"

[not_run]
"skills/catalog/SKILL.md#Database[1]" = "grammar, not a statement"

[[step]]
id = "database"
kind = "fixture"
channel = "vql"
vql = "SELECT 1;"
"""


class ManifestSectionsTest(unittest.TestCase):
    def setUp(self):
        self.path = Path(tempfile.mkdtemp()) / "chain.toml"

    def load(self, text):
        self.path.write_text(text, encoding="utf-8")
        return load_chain(self.path)

    def test_dialect_tables_and_not_run_are_read(self):
        chain = self.load(MANIFEST)
        self.assertEqual(chain.dialects["sqlserver"], {"write_identity": "INT IDENTITY(1001,1)"})
        self.assertEqual(chain.dialects["postgresql"]["write_timestamp"], "TIMESTAMP(0)")
        self.assertEqual(chain.not_run, {"skills/catalog/SKILL.md#Database[1]": "grammar, not a statement"})

    def test_a_manifest_without_them_has_empty_ones(self):
        chain = self.load('[[step]]\nid = "a"\nkind = "fixture"\nchannel = "vql"\nvql = "SELECT 1;"\n')
        self.assertEqual(chain.dialects, {})
        self.assertEqual(chain.not_run, {})

    def test_a_not_run_entry_needs_a_reason(self):
        with self.assertRaisesRegex(ChainError, "not_run"):
            self.load(MANIFEST.replace('= "grammar, not a statement"', "= 3"))

    def test_a_dialect_must_be_a_table_of_strings(self):
        with self.assertRaisesRegex(ChainError, "dialects"):
            self.load(MANIFEST.replace('write_identity = "INT IDENTITY(1001,1)"', "write_identity = [1]"))

    def test_known_keys_are_the_values_and_every_dialect_key(self):
        chain = self.load(MANIFEST)
        self.assertEqual(chain.known_values(),
                         {"database", "fixture_base", "write_dialect", "write_identity", "write_timestamp"})


class ValuesFileTest(unittest.TestCase):
    KNOWN = {"database", "fixture_base", "write_identity"}

    def setUp(self):
        self.path = Path(tempfile.mkdtemp()) / "verify.toml"

    def test_a_missing_file_gives_nothing(self):
        self.assertEqual(load_values_file(self.path, "lab", self.KNOWN), {})

    def test_only_the_profile_s_own_table_is_read(self):
        self.path.write_text('[dev]\nfixture_base = "/a"\n[lab]\nfixture_base = "/b"\n', encoding="utf-8")
        self.assertEqual(load_values_file(self.path, "lab", self.KNOWN), {"fixture_base": "/b"})
        self.assertEqual(load_values_file(self.path, "prod", self.KNOWN), {})

    def test_an_unknown_key_names_the_file_the_table_and_the_known_keys(self):
        self.path.write_text('[lab]\nfixture_bas = "/b"\n', encoding="utf-8")
        with self.assertRaises(ChainError) as caught:
            load_values_file(self.path, "lab", self.KNOWN)
        message = str(caught.exception)
        self.assertIn(str(self.path), message)
        self.assertIn("[lab]", message)
        self.assertIn("fixture_bas", message)
        self.assertIn("fixture_base", message)

    def test_numbers_are_read_as_text(self):
        self.path.write_text('[lab]\nfixture_base = 7\n', encoding="utf-8")
        self.assertEqual(load_values_file(self.path, "lab", self.KNOWN), {"fixture_base": "7"})

    def test_a_table_inside_the_profile_table_is_refused(self):
        self.path.write_text('[lab.fixture_base]\nx = 1\n', encoding="utf-8")
        with self.assertRaisesRegex(ChainError, "fixture_base"):
            load_values_file(self.path, "lab", self.KNOWN)

    def test_a_file_that_is_not_toml_is_refused(self):
        self.path.write_text('[lab\n', encoding="utf-8")
        with self.assertRaisesRegex(ChainError, "verify.toml"):
            load_values_file(self.path, "lab", self.KNOWN)

    def test_a_profile_entry_that_is_not_a_table_is_refused(self):
        self.path.write_text('lab = "x"\n', encoding="utf-8")
        with self.assertRaisesRegex(ChainError, r"\[lab\]"):
            load_values_file(self.path, "lab", self.KNOWN)


def profile(**over):
    base = dict(name="lab", host="h", port=9996, database="admin", user="admin", password="p",
                production=False, transport="vql_psycopg2", marketplace_url=None, marketplace_server_id=None)
    base.update(over)
    return Profile(**base)


class Server:
    """A fake Virtual DataPort that answers the feature probe the way 9.5.1 does.

    ``settings`` is what ``GET_PARAMETER`` reads (``None`` = refused, a non-administrator);
    ``adapter``/``catalog`` the cache database; every other statement is accepted and recorded.
    """
    sent: list[str] = []
    settings: dict | None = {"llm_enabled": "true", "llm_model": "gpt-5.1",
                             "embedding_model": "text-embedding-3-large"}
    adapter, catalog, plus, impersonation = "sqlserver", "enterprise_data", True, True

    def __init__(self, profile, database=None):
        self.database = database

    def execute(self, statement):
        Server.sent.append(statement)
        if "VALIDATE_MPP_LICENSE" in statement:
            return VqlResult(statement, ["max_processors", "current_processors", "status", "details"],
                             [[2147483647 if Server.plus else -1, -1, -5, "x"]])
        if "GET_CACHE_CONFIGURATION" in statement:
            return VqlResult(statement, ["database_datasource_name", "datasource_name", "adapter_database_name",
                                         "adapter_database_version", "status", "target_catalog", "target_schema"],
                             [["admin", "vdpcachedatasource", Server.adapter, "1", "ON", Server.catalog, "dbo"]])
        if "GET_PARAMETER" in statement:
            if Server.settings is None:
                raise RuntimeError("Error executing query.")
            names = [part.split("'")[0] for part in statement.split("SELECT '")[1:]]
            return VqlResult(statement, ["name", "property_value"], [[n, Server.settings.get(n)] for n in names])
        if statement.startswith("DESC USER"):
            return VqlResult(statement, ["name", "adminglobal"], [["admin", "true"]])
        if "impersonate_user" in statement and "probe" in statement:
            if not Server.impersonation:
                raise RuntimeError("This user cannot impersonate.")
            return VqlResult(statement, ["probe"], [[1]])
        if statement.upper().startswith("SELECT"):
            return VqlResult(statement, ["c"], [["x"]])
        return VqlResult(statement, None, None)

    def close(self):
        pass


def reset_server(**over):
    Server.sent = []
    Server.settings = {"llm_enabled": "true", "llm_model": "gpt-5.1", "embedding_model": "text-embedding-3-large"}
    Server.adapter, Server.catalog, Server.plus, Server.impersonation = "sqlserver", "enterprise_data", True, True
    for key, value in over.items():
        setattr(Server, key, value)


