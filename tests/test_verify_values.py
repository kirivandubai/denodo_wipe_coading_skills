class RequiresTest(unittest.TestCase):
    def setUp(self):
        reset_server()
        self.dir = Path(tempfile.mkdtemp())
        self.path = self.dir / "chain.toml"
        self.path.write_text(REQUIRES, encoding="utf-8")

    def test_a_step_runs_when_the_server_has_what_it_requires(self):
        doc, code = run_chain(profile(), load_chain(self.path), root=self.dir, vql_factory=Server)
        self.assertEqual(code, 0, doc)
        self.assertEqual([s["skipped"] for s in doc["steps"]], [False, False])

    def test_a_missing_feature_skips_the_step_saying_why(self):
        reset_server(plus=False, impersonation=False)
        doc, code = run_chain(profile(), load_chain(self.path), root=self.dir, vql_factory=Server)
        self.assertEqual(code, 0, doc)
        tags, someone = doc["steps"]
        self.assertTrue(tags["skipped"])
        self.assertIn("enterprise_plus", tags["reason"])
        self.assertIn("Enterprise Plus", tags["reason"])
        self.assertIn("impersonat", someone["reason"])
        self.assertNotIn("CREATE TAG verify_pii", Server.sent)

    def test_an_unknown_feature_runs_the_step(self):
        class Silent(Server):
            def execute(self, statement):
                if "VALIDATE_MPP_LICENSE" in statement or "GET_CACHE_CONFIGURATION" in statement:
                    raise RuntimeError("no")
                return super().execute(statement)

        doc, code = run_chain(profile(), load_chain(self.path), root=self.dir, vql_factory=Silent)
        self.assertEqual([s["skipped"] for s in doc["steps"]], [False, False])
        self.assertIsNone(doc["features"]["enterprise_plus"])

    def test_an_unknown_requirement_is_a_manifest_error(self):
        self.path.write_text(REQUIRES.replace('"cache"]', '"caches"]'), encoding="utf-8")
        with self.assertRaisesRegex(ChainError, "caches"):
            load_chain(self.path)


